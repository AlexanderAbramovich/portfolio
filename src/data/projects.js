// блок кейса-кампании: слайдеры до/после + чистовики + фото на объекте
const camp = (folder, slug, title, titleEn, opts = {}) => {
  const base = `${BASE}images/projects/${folder}/${slug}`
  return {
    slug,
    title,
    titleEn,
    pairs: (opts.pairs || []).map((pr, i) => ({
      before: `${base}/pair-${i + 1}-before.jpg`,
      after: `${base}/pair-${i + 1}-after.jpg`,
      mode: pr.mode || 'slider',
      what: pr.what,
      whatEn: pr.whatEn,
    })),
    images: Array.from({ length: opts.clean || 0 }, (_, i) => `${base}/${i + 1}.jpg`),
    photos: Array.from({ length: opts.photos || 0 }, (_, i) => `${base}/photo-${i + 1}.jpg`),
    ...(opts.layout ? { layout: opts.layout } : {}),
    ...(opts.ar ? { ar: opts.ar } : {}),
    ...(opts.pack ? { pack: opts.pack } : {}),
    ...(opts.pairCols ? { pairCols: opts.pairCols } : {}),
    ...(opts.videos ? {
      videos: Array.from({ length: opts.videos }, (_, i) => `${base}/${i + 1}.mp4`),
      posters: Array.from({ length: opts.videos }, (_, i) => `${base}/poster-${i + 1}.jpg`),
    } : {}),
    ...(opts.note ? { note: opts.note, noteEn: opts.noteEn } : {}),
  }
}

